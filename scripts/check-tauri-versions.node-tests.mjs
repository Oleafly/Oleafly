test("pre-release and build metadata do not count, as in tauri build", () => {
  const matches = (crateVersion, npmVersion) =>
    compare([["tauri", crateVersion]], { "@tauri-apps/api": npmVersion }).pairs[0].matches;
  assert.equal(matches("2.12.0-rc.1", "2.12.3"), true);
  assert.equal(matches("2.12.0", "2.12.0-beta.2"), true);
  assert.equal(matches("2.11.2", "2.11.0+sha.5114f85"), true);
  assert.equal(matches("2.12.0-beta.2", "2.11.9"), false);
  assert.equal(matches("3.0.0-alpha.1", "2.99.0"), false);
});

test("an npm package with no crate in Cargo.lock is reported, not failed", async (t) => {
  const root = await fixture(t, {
    crates: [["tauri", "2.11.5"]],
    npm: { "@tauri-apps/api": "2.11.1", "@tauri-apps/plugin-fs": "2.5.0" },
    manifest: manifestWith('tauri = "2"'),
  });
  const result = runCheck(root);
  assert.equal(result.status, 0, result.stderr);
  assert.match(
    result.stdout,
    /@tauri-apps\/plugin-fs 2\.5\.0: tauri-plugin-fs is not in Cargo\.lock and src-tauri\/Cargo\.toml gives no version for it, so tauri build does not compare this pair either\./u,
  );
});

test("a duplicated crate falls back to an exact src-tauri/Cargo.toml version", async (t) => {
  const crates = [
    ["tauri", "2.11.5"],
    ["tauri-plugin-shell", "1.0.0"],
    ["tauri-plugin-shell", "2.3.6", PLUGINS_GIT],
  ];
  const npm = { "@tauri-apps/api": "2.11.1", "@tauri-apps/plugin-shell": "2.3.6" };

  const range = await fixture(t, {
    crates,
    npm,
    manifest: manifestWith('tauri-plugin-shell = "2"'),
  });
  const skipped = runCheck(range);
  assert.equal(skipped.status, 0, skipped.stderr);
  assert.match(
    skipped.stdout,
    /tauri-plugin-shell is listed 2 times in Cargo\.lock \(1\.0\.0, 2\.3\.6\) and src-tauri\/Cargo\.toml asks for "2", which is not an exact version/u,
  );

  const exact = await fixture(t, {
    crates,
    npm,
    manifest: manifestWith('tauri-plugin-shell = { version = "2.2.0", features = [] }'),
  });
  const compared = runCheck(exact);
  assert.equal(compared.status, 1);
  assert.match(
    compared.stderr,
    /tauri-plugin-shell 2\.2\.0 \(src-tauri\/Cargo\.toml\) and @tauri-apps\/plugin-shell 2\.3\.6 \(node_modules\)/u,
  );
});

test("unpaired npm packages and Rust-only crates are listed with a reason", async (t) => {
  const root = await fixture(t, {
    crates: [
      ["tauri", "2.11.5"],
      ["tauri-build", "2.6.3"],
      ["tauri-plugin", "2.6.3"],
      ["tauri-plugin-playwright", "0.4.1", ""],
    ],
    npm: {
      "@tauri-apps/api": "2.11.1",
      "@tauri-apps/cli": "2.11.4",
      "@tauri-apps/toml": "2.2.4",
    },
  });
  const result = runCheck(root);
  assert.equal(result.status, 0, result.stderr);
  assert.match(
    result.stdout,
    /@tauri-apps\/cli 2\.11\.4: this is the Tauri CLI\. It pairs with the tauri-cli crate/u,
  );
  assert.match(result.stdout, /@tauri-apps\/toml 2\.2\.4: no Rust crate pairs with it\./u);
  assert.match(
    result.stdout,
    /tauri-plugin-playwright 0\.4\.1: no @tauri-apps\/plugin-playwright package in node_modules/u,
  );
  assert.doesNotMatch(result.stdout, /tauri-build|tauri-plugin 2\.6\.3/u);
});

test("the check fails closed when nothing is compared or an input is missing", async (t) => {
  const onlyCli = await fixture(t, {
    crates: [["tauri", "2.11.5"]],
    npm: { "@tauri-apps/cli": "2.11.4" },
  });
  const nothing = runCheck(onlyCli);
  assert.equal(nothing.status, 1);
  assert.match(
    nothing.stderr,
    /no @tauri-apps package in node_modules pairs with a crate in Cargo\.lock/u,
  );

  const noModules = await fixture(t, { crates: [["tauri", "2.11.5"]] });
  const uninstalled = runCheck(noModules);
  assert.equal(uninstalled.status, 1);
  assert.match(uninstalled.stderr, /does not exist\. Run pnpm install first\./u);

  const noLock = await fixture(t, { npm: { "@tauri-apps/api": "2.11.1" } });
  await rm(join(noLock, "Cargo.lock"));
  const unlocked = runCheck(noLock);
  assert.equal(unlocked.status, 1);
  assert.match(unlocked.stderr, /Cargo\.lock does not exist/u);
});

test("Cargo.lock parsing reads [[package]] tables only and accepts CRLF", () => {
  const text = [
    lockText([["tauri", "2.11.5"]], "\r\n"),
    "[[patch.unused]]",
    'name = "tauri-plugin-updater"',
    'version = "9.9.9"',
    "",
    "[metadata]",
    '"checksum tauri 2.11.5" = "abc"',
    "",
  ].join("\r\n");
  assert.deepEqual(readLockPackages(text), [
    { name: "tauri", version: "2.11.5", source: REGISTRY },
  ]);
});

test("src-tauri/Cargo.toml requirements are read from [dependencies] only", () => {
  const manifest = [
    "[package]",
    'version = "0.1.0"',
    "",
    "[build-dependencies]",
    'tauri-build = "2.6.3"',
    "",
    "[dependencies]",
    'tauri = { version = "2.11.0", features = ["unstable"] }',
    "tauri-plugin-os = '2.3.2'",
    'tauri-plugin-fs = { features = ["watch"], version = "2.5.0" }',
    'tauri-plugin-shell = { path = "../plugins/shell" }',
    "",
    "[target.'cfg(windows)'.dependencies]",
    'tauri-plugin-dialog = "2.7.3"',
  ].join("\n");
  assert.equal(declaredRequirement(manifest, "tauri"), "2.11.0");
  assert.equal(declaredRequirement(manifest, "tauri-plugin-os"), "2.3.2");
  assert.equal(declaredRequirement(manifest, "tauri-plugin-fs"), "2.5.0");
  assert.equal(declaredRequirement(manifest, "tauri-plugin-shell"), undefined);
  assert.equal(declaredRequirement(manifest, "tauri-plugin-dialog"), undefined);
  assert.equal(declaredRequirement(manifest, "tauri-build"), undefined);
  assert.equal(declaredRequirement(undefined, "tauri"), undefined);
});

test("version parsing follows the semver grammar that tauri build uses", () => {
  const valid = [
    "0.0.0",
    "2.11.0",
    "2.11.0-rc.1",
    "1.0.0-alpha-a.b-c",
    "1.0.0+001",
    "1.0.0-0.3.7+exp.sha.5114f85",
  ];
  const invalid = [
    "2",
    "2.11",
    "v2.11.0",
    "=2.11.0",
    "02.11.0",
    "2.11.0.1",
    "2.11.0-",
    "2.11.0-01",
    "2.11.0+",
    "2.11.0-a..b",
    " 2.11.0",
    "2.x.0",
    undefined,
  ];
  for (const version of valid) assert.notEqual(parseVersion(version), undefined, version);
  for (const version of invalid) assert.equal(parseVersion(version), undefined, String(version));
  assert.deepEqual(parseVersion("2.12.0-beta.2+b7"), {
    major: "2",
    minor: "12",
    patch: "0",
    prerelease: "beta.2",
    build: "b7",
  });
  assert.equal(sameMajorMinor(parseVersion("2.11.9"), parseVersion("2.11.0")), true);
  assert.equal(sameMajorMinor(parseVersion("2.11.0"), parseVersion("2.1.10")), false);
});

test("npm names map to crates the way tauri build pairs them", () => {
  assert.equal(crateForNpmPackage("@tauri-apps/api"), "tauri");
  assert.equal(crateForNpmPackage("@tauri-apps/plugin-updater"), "tauri-plugin-updater");
  assert.equal(crateForNpmPackage("@tauri-apps/plugin-cli"), "tauri-plugin-cli");
  assert.equal(crateForNpmPackage("@tauri-apps/cli"), undefined);
  assert.equal(crateForNpmPackage("@tauri-apps/plugin-"), undefined);
  assert.equal(crateForNpmPackage("@srsholmes/tauri-playwright"), undefined);
});

test("CLI arguments fail closed", () => {
  assert.equal(parseArgs(["--root", "fixtures"]).root, resolve("fixtures"));
  assert.equal(parseArgs(["--root=fixtures"]).root, resolve("fixtures"));
  assert.equal(parseArgs(["--help"]).help, true);
  assert.throws(() => parseArgs(["--root"]), /--root requires a directory/u);
  assert.throws(() => parseArgs(["--root="]), /--root requires a directory/u);
  assert.throws(() => parseArgs(["--strict"]), /unknown option: --strict/u);
  const help = spawnSync(process.execPath, [CHECK_PATH, "--help"], { encoding: "utf8" });
  assert.equal(help.status, 0);
  assert.match(help.stdout, /--root <dir>/u);
});

test("package scripts and the Frontend CI job run the check before anything else", async () => {
  const [packageSource, workflowSource] = await Promise.all([
    readFile(join(ROOT, "package.json"), "utf8"),
    readFile(join(ROOT, ".github", "workflows", "ci.yml"), "utf8"),
  ]);
  const { scripts } = JSON.parse(packageSource);
  assert.equal(scripts["tauri-versions:check"], "node scripts/check-tauri-versions.mjs");
  assert.equal(
    scripts["tauri-versions:test"],
    "node --test scripts/check-tauri-versions.node-tests.mjs",
  );
  const lines = workflowSource.replace(/\r\n/gu, "\n").split("\n");
  const start = lines.indexOf("  frontend:");
  assert.notEqual(start, -1, "ci.yml must have a frontend job");
  const next = lines.findIndex(
    (line, index) => index > start && /^ {2}[A-Za-z0-9_-]+:\s*$/u.test(line),
  );
  const runs = lines
    .slice(start, next === -1 ? lines.length : next)
    .map((line) => line.trim())
    .filter((line) => line.startsWith("run: "));
  const install = runs.indexOf("run: pnpm install --frozen-lockfile");
  assert.notEqual(install, -1, "the frontend job must install dependencies");
  assert.equal(runs[install + 1], "run: pnpm tauri-versions:check");
});
