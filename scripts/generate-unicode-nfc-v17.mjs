import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const unicodeVersion = "17.0.0";
const sources = [
  {
    name: "UnicodeData.txt",
    sha256: "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
  },
  {
    name: "CompositionExclusions.txt",
    sha256: "2f239196ef3b5b61db5cc476e9bd80f534d15aa1b74e1be1dea5d042a344c85f",
  },
];

const loaded = new Map();
for (const source of sources) {
  const response = await fetch(
    `https://www.unicode.org/Public/${unicodeVersion}/ucd/${source.name}`,
  );
  if (!response.ok) throw new Error(`failed to fetch ${source.name}: ${response.status}`);
  const text = await response.text();
  const digest = createHash("sha256").update(text).digest("hex");
  if (digest !== source.sha256) {
    throw new Error(`${source.name} digest ${digest} does not match the pinned source`);
  }
  loaded.set(source.name, text);
}

const exclusions = new Set(
  loaded.get("CompositionExclusions.txt")
    .split("\n")
    .map((line) => line.replace(/#.*/, "").trim())
    .filter(Boolean)
    .map((value) => Number.parseInt(value, 16)),
);
const combiningClasses = [];
const decompositions = [];
const compositions = [];
for (const line of loaded.get("UnicodeData.txt").split("\n")) {
  if (!line) continue;
  const fields = line.split(";");
  const codePoint = Number.parseInt(fields[0], 16);
  const combiningClass = Number.parseInt(fields[3], 10);
  if (combiningClass !== 0) combiningClasses.push(codePoint, combiningClass);
  const rawDecomposition = fields[5];
  if (!rawDecomposition || rawDecomposition.startsWith("<")) continue;
  const decomposition = rawDecomposition
    .split(" ")
    .map((value) => Number.parseInt(value, 16));
  decompositions.push(codePoint, decomposition.length, ...decomposition);
  if (decomposition.length === 2 && !exclusions.has(codePoint)) {
    compositions.push(decomposition[0], decomposition[1], codePoint);
  }
}

const output = `// Generated by scripts/generate-unicode-nfc-v17.mjs. Do not edit.\n` +
  `// Unicode ${unicodeVersion}; source SHA-256 values are pinned in the generator.\n` +
  `export const UNICODE_NFC_VERSION = "${unicodeVersion}" as const;\n` +
  `export const NFC_COMBINING_CLASSES = ${JSON.stringify(combiningClasses)} as const;\n` +
  `export const NFC_DECOMPOSITIONS = ${JSON.stringify(decompositions)} as const;\n` +
  `export const NFC_COMPOSITIONS = ${JSON.stringify(compositions)} as const;\n`;
const outputPath = fileURLToPath(
  new URL("../packages/realtime-protocol/src/unicode-nfc-v17.generated.ts", import.meta.url),
);
await writeFile(outputPath, output);
