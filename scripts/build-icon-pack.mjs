// Builds the downloadable colour icon pack from icon-packs/oleafly-color/ into one JSON file,
// and pins its SHA-256 in src/lib/icon-pack-pin.ts. The app downloads this file and installs it
// only when someone picks the Color pack. The one part that ships is the preview on the Color
// card in Settings: four drawings and their styles, written to src/components/settings/.
//
//   node scripts/build-icon-pack.mjs
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { createServer } from "vite";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packDir = join(root, "icon-packs/oleafly-color");
const out = join(packDir, "dist/oleafly-color.json");
// The Color card's preview, in the order it shows them.
const PREVIEW = ["folder", "search", "settings", "assistant", "source-control", "research", "figure", "terminal"];

const server = await createServer({
  root,
  configFile: join(root, "vite.config.ts"),
  server: { middlewareMode: true, hmr: false },
  appType: "custom",
  logLevel: "error",
});
try {
  const icons = await server.ssrLoadModule("/icon-packs/oleafly-color/index.tsx");
  const { OleaflyIconDefs } = await server.ssrLoadModule("/icon-packs/oleafly-color/OleaflyIconDefs.tsx");

  const inner = (markup) => markup.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  const drawn = {};
  for (const [exportName, Icon] of Object.entries(icons)) {
    if (!exportName.startsWith("Oi") || !Icon || typeof Icon === "string") continue;
    const markup = renderToStaticMarkup(createElement(Icon));
    const name = markup.match(/data-oleafly-icon="([^"]+)"/)?.[1];
    if (!name) throw new Error(`${exportName} rendered without a name`);
    drawn[name] = inner(markup);
  }
  const defs = renderToStaticMarkup(createElement(OleaflyIconDefs)).replace(/^[\s\S]*?<defs>/, "").replace(/<\/defs>[\s\S]*$/, "");
  const iconCss = readFileSync(join(packDir, "oleafly-icons.css"), "utf8");
  const pack = {
    format: 1,
    id: "oleafly-color",
    version: 1,
    css: `${iconCss}\n${readFileSync(join(packDir, "interface.css"), "utf8")}`,
    defs,
    icons: Object.fromEntries(Object.entries(drawn).sort(([a], [b]) => a.localeCompare(b))),
  };
  // The preview leaves out interface.css, which restyles every Lucide icon in the app.
  if (PREVIEW.some((name) => !drawn[name])) throw new Error("a preview icon is missing from the pack");
  const preview = { ...pack, id: "oleafly-color-preview", css: iconCss, icons: Object.fromEntries(PREVIEW.map((name) => [name, drawn[name]])) };
  writeFileSync(
    join(root, "src/components/settings/icon-pack-preview.ts"),
    `// Generated by scripts/build-icon-pack.mjs; rebuild the pack to update it.\n// The Color card shows these drawings before the pack is downloaded. The rest of the pack is a download.\nexport const COLOR_ICON_PREVIEW = ${JSON.stringify(JSON.stringify(preview))};\n`,
  );
  const json = JSON.stringify(pack);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, json);
  const sha256 = createHash("sha256").update(json).digest("hex");
  writeFileSync(
    join(root, "src/lib/icon-pack-pin.ts"),
    `// Generated by scripts/build-icon-pack.mjs; rebuild the pack to update it.\nexport const COLOR_ICON_PACK = {\n  file: "oleafly-color.json",\n  version: ${pack.version},\n  bytes: ${Buffer.byteLength(json)},\n  sha256: "${sha256}",\n} as const;\n`,
  );
  console.log(`${Object.keys(drawn).length} icons, ${Buffer.byteLength(json)} bytes, sha256 ${sha256}`);
} finally {
  await server.close();
}
