pub(crate) fn new_computer_modern_upright_has(character: char) -> bool {
    let code = character as u32;
    let following = NEW_COMPUTER_MODERN_UPRIGHT.partition_point(|(start, _)| *start <= code);
    code < 0xA0
        || NEW_COMPUTER_MODERN_UPRIGHT[..following]
            .last()
            .is_some_and(|(_, end)| code <= *end)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_upright_faces_have_phonetic_greek_and_cyrillic_letters_but_no_cjk() {
        for character in "\u{2d0}\u{26a}\u{251}\u{283}\u{292}\u{14b}\u{3b8}\u{416}a".chars() {
            assert!(new_computer_modern_upright_has(character), "{character}");
        }
        for character in "\u{4e2d}\u{3042}\u{d55c}\u{a7ae}".chars() {
            assert!(!new_computer_modern_upright_has(character), "{character}");
        }
    }

    #[test]
    fn the_ranges_are_sorted_and_apart() {
        assert!(NEW_COMPUTER_MODERN_UPRIGHT
            .windows(2)
            .all(|pair| pair[0].0 <= pair[0].1 && pair[0].1 + 1 < pair[1].0));
    }
}
